// Pure helpers for investigation reports: citation parsing and Markdown export.
import type { Investigation, InvestigationSource } from '../types/api'

export type TextPart =
  | { kind: 'text'; text: string }
  | { kind: 'cite'; numbers: number[]; unverified: boolean; requirement: boolean }
  | { kind: 'flag'; text: string }

const CITE = /\[((?:\d+|unverified|R)(?:\s*,\s*(?:\d+|unverified|R))*)\]|\[(quote not found in sources|uncited claim|attribution not supported)\]/g

/** Split text containing [1], [2, 3], [R] (user requirement), [unverified] or quote flags into parts. */
export function splitCitations(text: string): TextPart[] {
  const parts: TextPart[] = []
  let last = 0
  for (const m of text.matchAll(CITE)) {
    if (m.index! > last) parts.push({ kind: 'text', text: text.slice(last, m.index) })
    if (m[2]) {
      parts.push({ kind: 'flag', text: m[2] })
    } else {
      const tokens = m[1].split(',').map((t) => t.trim())
      parts.push({
        kind: 'cite', numbers: tokens.filter((t) => /^\d+$/.test(t)).map(Number),
        unverified: tokens.includes('unverified'), requirement: tokens.includes('R'),
      })
    }
    last = m.index! + m[0].length
  }
  if (last < text.length) parts.push({ kind: 'text', text: text.slice(last) })
  return parts
}

/** Strip light Markdown emphasis for plain-text display. */
export function plain(text: string): string {
  return text.replace(/\*\*(.+?)\*\*/g, '$1').replace(/(^|[^*])\*(?!\s)(.+?)\*(?!\*)/g, '$1$2').replace(/`([^`]+)`/g, '$1')
}

export function sourceLabel(s: Pick<InvestigationSource, 'paper_title' | 'page'>): string {
  return `${s.paper_title ?? 'Untitled paper'}${s.page ? `, p. ${s.page}` : ''}`
}

const cites = (ns: number[]) => (ns.length ? ` [${ns.join(', ')}]` : '')
const oneLine = (t: string) => t.replace(/\s+/g, ' ').trim()

/** Remove the agent report's title and its References section (the export has its own Sources list). */
function narrativeBody(markdown: string): string {
  return markdown
    .replace(/^\s*#\s+[^\n]*\n+/, '')
    .replace(/\n## References\n[\s\S]*$/, '')
    .trim()
}

export function reportFilename(inv: Pick<Investigation, 'question' | 'created_at'>): string {
  const slug = inv.question.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || 'investigation'
  return `researchmind-${inv.created_at.slice(0, 10)}-${slug}.md`
}

/** Full Markdown export of a completed investigation, with numbered, page-level sources. */
export function buildMarkdownExport(inv: Investigation): string {
  const r = inv.result
  const out: string[] = [`# Investigation: ${inv.question}`, '']
  out.push(`- **Status:** ${inv.status}`)
  if (r) out.push(`- **Mode:** ${r.mode === 'llm' ? `LLM report (${inv.provider ?? 'LLM'} / ${inv.model ?? 'model'}) grounded in MCP graph tools` : 'Offline extractive plan with MCP graph tools (no LLM)'}`)
  out.push(`- **Started:** ${inv.started_at ?? inv.created_at}`)
  if (inv.duration_seconds != null) out.push(`- **Duration:** ${inv.duration_seconds.toFixed(1)} s`)
  if (r) out.push(`- **Confidence:** ${r.confidence.level}`, `- **Evidence:** ${r.sources.length} passages from ${r.papers.length} papers`)
  out.push('', '> Generated by ResearchMind AI from the ingested papers only. Candidate research gaps are hypotheses to verify against the wider literature, not confirmed novel findings.', '')

  if (!r) {
    out.push('## Error', '', inv.error?.message ?? 'No result available.', '')
    return out.join('\n')
  }

  if (inv.requirements) out.push('## Your requirements [R]', '', '_User-provided, not from the papers._', '', inv.requirements, '')
  out.push('## Summary', '', r.summary, '')

  out.push('## Evidence-backed findings', '')
  if (!r.findings.length) out.push('_No findings were retrieved for this question._')
  for (const f of r.findings) out.push(`- **${f.type}** — ${oneLine(f.text)} — *${f.paper_title ?? f.paper_id}*${f.page ? `, p. ${f.page}` : ''}${cites(f.citations)}`)
  out.push('')

  out.push('## Cross-paper comparisons', '')
  const conflicts = r.comparisons.filter((c) => c.kind === 'contradiction')
  const related = r.comparisons.filter((c) => c.kind === 'related')
  if (!r.comparisons.length) out.push('_No cross-paper conflicts or closely related statements were detected._', '')
  if (conflicts.length) {
    out.push('### Conflicting results', '')
    for (const c of conflicts) {
      out.push(`- *${c.a.paper_title}* (p. ${c.a.page ?? '?'}): "${oneLine(c.a.text)}" [${c.a.citation}]`,
        `  - vs. *${c.b.paper_title}* (p. ${c.b.page ?? '?'}): "${oneLine(c.b.text)}" [${c.b.citation}]`,
        `  - similarity ${c.score.toFixed(2)}. ${c.note}`)
    }
    out.push('')
  }
  if (related.length) {
    out.push('### Closely related statements', '')
    for (const c of related) {
      out.push(`- "${oneLine(c.a.text)}" — *${c.a.paper_title}* [${c.a.citation}]`, `  - ~ "${oneLine(c.b.text)}" — *${c.b.paper_title}* [${c.b.citation}]`)
    }
    out.push('')
  }
  if (r.method_comparison.length) {
    out.push('### Methods and datasets across papers', '', '| Entity | Type | Papers |', '|---|---|---|')
    for (const m of r.method_comparison) {
      out.push(`| ${m.entity} | ${m.type} | ${m.papers.map((p) => `${p.paper_title ?? p.paper_id} [${p.citation}]`).join('; ')} |`)
    }
    out.push('')
  }

  out.push('## Candidate research gaps', '', '_Hypotheses supported by evidence in the ingested papers — not claims of novelty._', '')
  if (!r.gaps.length) out.push('_No candidate gaps with verifiable evidence were found._', '')
  for (const g of r.gaps) {
    out.push(`### ${g.id}. ${oneLine(g.title)}`, '', `- **Type:** ${g.type.replace(/_/g, ' ')}${g.score != null ? ` · score ${g.score}` : ''}`,
      `- **Why:** ${g.rationale}${cites(g.citations)}`)
    for (const e of g.evidence) out.push(`- Evidence [${e.citation}]: *${e.paper_title}*${e.page ? `, p. ${e.page}` : ''} — "${oneLine(e.quote)}"`)
    out.push('')
  }

  if (r.inferences.length) {
    out.push('## Model inferences (not stated in the papers)', '')
    for (const x of r.inferences) out.push(`- Hypothesis: ${oneLine(x.text)}`)
    out.push('')
  }
  if (r.open_questions.length) {
    out.push('## Not answered by the evidence', '')
    for (const q of r.open_questions) out.push(`- ${oneLine(q)}`)
    out.push('')
  }
  out.push('## Limitations of the evidence', '')
  if (!r.limitations.length) out.push('_No limitations were extracted for the relevant papers._')
  for (const l of r.limitations) out.push(`- *${l.paper_title}* (${l.kind === 'future_work' ? 'future work' : 'limitation'}): ${oneLine(l.text)}${cites(l.citations)}`)
  out.push('')

  out.push('## Confidence and uncertainty', '', `**Confidence: ${r.confidence.level}**`, '')
  for (const x of r.confidence.reasons) out.push(`- ${x}`)
  for (const x of r.confidence.uncertainties) out.push(`- ⚠ ${x}`)
  if (r.confidence.narrative) out.push('', `Agent's assessment: ${r.confidence.narrative}`)
  out.push('')

  if (r.warnings.length) {
    out.push('## Warnings', '')
    for (const w of r.warnings) out.push(`- ${w}`)
    out.push('')
  }

  const narrative = narrativeBody(r.report_markdown)
  if (narrative) out.push('## Narrative report', '', narrative.replace(/^## /gm, '### '), '')

  out.push('## Sources', '')
  for (const s of r.sources) {
    out.push(`${s.n}. *${s.paper_title ?? s.paper_id}*${s.year ? ` (${s.year})` : ''}${s.page ? `, p. ${s.page}` : ''}${s.section ? `, ${s.section}` : ''} — "${oneLine(s.quote)}" \`${s.chunk_id}\``)
  }
  out.push('')

  out.push('## Investigation trace', '')
  for (const st of r.steps) out.push(`- \`${st.tool}\`${st.source === 'coverage' ? ' (coverage)' : ''}: ${st.summary}`)
  out.push('')
  return out.join('\n')
}

export function downloadText(filename: string, text: string): void {
  const url = URL.createObjectURL(new Blob([text], { type: 'text/markdown;charset=utf-8' }))
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}
